#!/usr/bin/env node
// AUTO-pull content sync for the Petal docs site (issue #437).
//
// Pulls the three source-of-truth docs that live in the main repo tree and
// turns them into Starlight pages/fragments under src/content/docs and
// src/fragments. This keeps a single source of truth for content that also
// needs to be correct for engineers working in the repo (SELF_HOSTING.md,
// the backend README, the web-harness README) instead of hand-copying prose
// that will drift.
//
// Modes:
//   node sync-auto-content.mjs                 sync content from current
//                                               source files (used by
//                                               `npm run build` / `npm run dev`)
//   node sync-auto-content.mjs --check-drift    CI gate: fail if a source file
//                                               changed since the hash pinned
//                                               in auto-content-manifest.json
//   node sync-auto-content.mjs --update-manifest  after reviewing a source
//                                               change (incl. for PII), pin
//                                               its new hash in the manifest
//
// Generated destination files are NOT committed (see repo .gitignore) — they
// are always rebuilt from the current source at build/dev time. The manifest
// hash is the thing that IS committed, and it exists purely so CI can force a
// human to look at upstream changes (see --check-drift) rather than silently
// republishing whatever the source docs say today.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = resolve(SITE_ROOT, '..');
const MANIFEST_PATH = join(SITE_ROOT, 'scripts', 'auto-content-manifest.json');

const AUTO_GENERATED_NOTICE = (source) =>
	`<!--\n  AUTO-GENERATED by site/scripts/sync-auto-content.mjs from ${source}.\n  Do not edit this file directly — edit the source file and re-run\n  \`npm run sync:auto\` (or \`npm run build\`, which runs it automatically).\n-->\n\n`;

function sha256(text) {
	return createHash('sha256').update(text, 'utf8').digest('hex');
}

function stripLeadingH1(text) {
	return text.replace(/^#[ \t]+.+\r?\n+/, '');
}

/**
 * Strips internal GitHub issue-number references (e.g. "#123", "(#123)",
 * "(#103/#104)", "— #103/#104,") so the published page doesn't leak this
 * repo's private issue-tracker numbering. Order matters: the more specific
 * patterns (dash-prefixed lists, full parenthetical refs) must run before
 * the generic bare "#123" removal, or they get mangled instead of cleanly
 * removed.
 *
 * Only runs on prose (see `mapProseOutsideCodeFences` below) — the cleanup
 * regexes are deliberately narrow (they only touch whitespace immediately
 * next to a removed ref) so they can't rewrite unrelated indentation or
 * punctuation elsewhere in the document.
 */
function stripIssueRefs(text) {
	let out = text;
	// "— #123" / "— #123/#124," dash-prefixed issue-ref lists.
	out = out.replace(/[ \t]*[—–-][ \t]*#\d+(?:[/,][ \t]*#?\d+)*,?/g, '');
	// Parenthetical issue refs: "(#123)" or "(#123/#124)".
	out = out.replace(/[ \t]*\(#\d+(?:[/,][ \t]*#?\d+)*\)/g, '');
	// Remaining bare refs, e.g. "issue #96" -> "the issue tracker".
	out = out.replace(/[ \t]*#\d+/g, '');
	// Clean up parens/whitespace-before-close-paren left dangling by the
	// removals above (e.g. "(the issue tracker )" -> "(the issue tracker)").
	out = out.replace(/\([ \t]*\)/g, '');
	out = out.replace(/[ \t]+\)/g, ')');
	return out;
}

/**
 * Applies `fn` to the prose portions of a Markdown document while leaving
 * fenced ``` code blocks byte-for-byte untouched. Source docs like
 * backend/README.md and web-harness/README.md contain real shell/JSON
 * examples (e.g. `livekit-server :7880`) that must never be touched by the
 * issue-ref/name regexes above — an earlier version of this script collapsed
 * whitespace inside a bash comment and broke it.
 */
function mapProseOutsideCodeFences(text, fn) {
	return text
		.split(/(```[\s\S]*?```)/g)
		.map((part, i) => (i % 2 === 0 ? fn(part) : part))
		.join('');
}

function trimTrailingLineWhitespace(text) {
	return text
		.split('\n')
		.map((line) => line.replace(/[ \t]+$/, ''))
		.join('\n');
}

/**
 * Redacts individually-identifying names that show up in source docs written
 * for repo contributors but that must never appear on the public docs site
 * (the site's hard PII rule). This is a deliberate, reviewed allowlist of
 * substitutions, not a generic scrubber; `--check-drift` forces a human to
 * look at every upstream change.
 *
 * The substitution table itself lives OUTSIDE this file: writing a real name
 * here would publish, in a public repository, exactly the string the redactor
 * exists to remove. Same untracked file the PII scanner reads — see
 * loadLocalPatterns() in scan-for-pii.mjs. Absent file = no substitutions,
 * which is correct for an outside contributor with no such names to redact.
 */
function redactKnownNames(text) {
	const file =
		process.env.PETAL_PII_PATTERNS_FILE ??
		join(SITE_ROOT, '.pii-patterns.local.json');
	if (!existsSync(file)) return text;
	const entries = JSON.parse(readFileSync(file, 'utf8'));
	let out = text;
	for (const { pattern, flags, replacement } of entries) {
		if (!replacement) continue;
		out = out.replace(new RegExp(pattern, flags?.includes('g') ? flags : `${flags ?? ''}g`), replacement);
	}
	return out;
}

/**
 * docs/SELF_HOSTING.md's relative repo-tree links (`../backend/README.md`
 * etc.) don't resolve inside the docs site, which has no page corresponding
 * 1:1 with every file in the repo. Point them at the actual site pages
 * instead — and drop the RELEASING.md link outright: release engineering is
 * explicitly out of scope for this site (contributor-internals content, and
 * RELEASING.md itself must never be referenced from here — see CLAUDE.md and
 * issue #437), so the target page doesn't exist.
 */
function rewriteSelfHostingLinks(text) {
	let out = text;
	out = out.replace(/\[`backend\/README\.md`\]\(\.\.\/backend\/README\.md\)/g, '[Backend API reference](/docs/customizing/backend-api/)');
	out = out.replace(/\[`web-harness\/README\.md`\]\(\.\.\/web-harness\/README\.md\)/g, '[Joining from a browser](/docs/using/joining-from-a-browser/)');
	// Drop the "For signed desktop release packaging, see RELEASING.md" aside
	// entirely (out of scope for this site's audience).
	out = out.replace(/ For signed desktop release\s*\r?\npackaging, see \[`RELEASING\.md`\]\(RELEASING\.md\)\./, '');
	return out;
}

const ENTRIES = [
	{
		id: 'self-hosting',
		source: 'docs/SELF_HOSTING.md',
		dest: 'site/src/content/docs/customizing/self-hosting.md',
		build(raw) {
			let body = stripLeadingH1(raw);
			body = rewriteSelfHostingLinks(body);
			body = trimTrailingLineWhitespace(body).trimEnd();
			const frontmatter = [
				'---',
				'title: Self-hosting Petal',
				'description: Run Petal against LiveKit and backend infrastructure you operate yourself.',
				'---',
				'',
			].join('\n');
			return frontmatter + AUTO_GENERATED_NOTICE('docs/SELF_HOSTING.md') + body + '\n';
		},
	},
	{
		id: 'backend-api',
		source: 'backend/README.md',
		dest: 'site/src/content/docs/customizing/backend-api.md',
		build(raw) {
			let body = stripLeadingH1(raw);
			body = mapProseOutsideCodeFences(body, stripIssueRefs);
			body = redactKnownNames(body);
			body = trimTrailingLineWhitespace(body).trimEnd();
			const frontmatter = [
				'---',
				'title: Backend API reference',
				'description: Endpoints, environment variables, and deployment for the Petal backend.',
				'---',
				'',
			].join('\n');
			return frontmatter + AUTO_GENERATED_NOTICE('backend/README.md') + body + '\n';
		},
	},
	{
		id: 'web-harness-fragment',
		source: 'web-harness/README.md',
		// Written outside src/content/docs on purpose: every file under
		// src/content/docs is a Starlight page and must satisfy docsSchema
		// (a required `title`, etc). This is a fragment to be imported into
		// the "Joining from a browser" page, not a page of its own.
		dest: 'site/src/fragments/web-harness-readme.md',
		build(raw) {
			let body = stripLeadingH1(raw);
			body = mapProseOutsideCodeFences(body, stripIssueRefs);
			body = redactKnownNames(body);
			body = trimTrailingLineWhitespace(body).trimEnd();
			return AUTO_GENERATED_NOTICE('web-harness/README.md') + body + '\n';
		},
	},
];

function loadManifest() {
	if (!existsSync(MANIFEST_PATH)) {
		return { entries: {} };
	}
	return JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
}

function saveManifest(manifest) {
	writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, '\t') + '\n');
}

function main() {
	const mode = process.argv[2];
	const manifest = loadManifest();
	manifest.entries ??= {};

	if (mode === '--check-drift') {
		let drifted = false;
		for (const entry of ENTRIES) {
			const sourcePath = join(REPO_ROOT, entry.source);
			if (!existsSync(sourcePath)) {
				console.error(`[sync-auto-content] MISSING source: ${entry.source}`);
				drifted = true;
				continue;
			}
			const raw = readFileSync(sourcePath, 'utf8');
			const currentHash = sha256(raw);
			const pinned = manifest.entries[entry.id]?.sha256;
			if (!pinned) {
				console.error(
					`[sync-auto-content] ${entry.source}: no pinned hash for "${entry.id}" — run \`npm run sync:auto -- --update-manifest\` after reviewing it.`,
				);
				drifted = true;
			} else if (pinned !== currentHash) {
				console.error(
					`[sync-auto-content] DRIFT: ${entry.source} changed since it was last pinned.\n` +
						`  pinned:  ${pinned}\n` +
						`  current: ${currentHash}\n` +
						'  Review the change (in particular for anything PII/secret-shaped), then run\n' +
						'  `npm run sync:auto -- --update-manifest` in site/ to pin the new hash.',
				);
				drifted = true;
			}
		}
		if (drifted) {
			console.error('\n[sync-auto-content] --check-drift FAILED.');
			process.exit(1);
		}
		console.log('[sync-auto-content] --check-drift OK — all AUTO sources match their pinned hash.');
		return;
	}

	// Default ("sync") and --update-manifest both regenerate the destination
	// files from the current source so `npm run build`/`npm run dev` always
	// publish what's on disk right now.
	for (const entry of ENTRIES) {
		const sourcePath = join(REPO_ROOT, entry.source);
		const destPath = join(REPO_ROOT, entry.dest);
		const raw = readFileSync(sourcePath, 'utf8');
		const rendered = entry.build(raw);

		mkdirSync(dirname(destPath), { recursive: true });
		writeFileSync(destPath, rendered);

		manifest.entries[entry.id] ??= {};
		manifest.entries[entry.id].source = entry.source;
		manifest.entries[entry.id].dest = entry.dest;
		if (mode === '--update-manifest') {
			manifest.entries[entry.id].sha256 = sha256(raw);
		}
		console.log(`[sync-auto-content] synced ${entry.source} -> ${entry.dest}`);
	}

	if (mode === '--update-manifest') {
		saveManifest(manifest);
		console.log('[sync-auto-content] manifest hashes updated.');
	}
}

main();
