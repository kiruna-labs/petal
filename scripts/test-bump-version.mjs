#!/usr/bin/env node
// Exercises the REAL scripts/bump-version.mjs CLI (not just its exported
// functions -- see the repo-wide "verify wiring, not just feasibility" rule)
// against a throwaway fixture repo, then mutation-checks the lockstep gate
// by deliberately desyncing Cargo.lock's `desktop` version and confirming
// scripts/version-lockstep.mjs actually catches it. That's the exact gap
// issue #671 item 6 calls out: "the current gate doesn't check it."

import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import assert from 'node:assert/strict';

const execFileAsync = promisify(execFile);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BUMP_SCRIPT = path.join(__dirname, 'bump-version.mjs');
const LOCKSTEP_SCRIPT = path.join(__dirname, 'version-lockstep.mjs');

function fail(message) {
  console.error(`FAIL: ${message}`);
  process.exitCode = 1;
}

// A decoy crate/package pinned at the SAME version string as `desktop` /
// the repo, in both Cargo.lock and the two package-lock.json files. If
// bump-version ever matched the wrong entry, these assertions catch it.
async function writeFixture(root, version) {
  await mkdir(path.join(root, 'apps/desktop/src-tauri'), { recursive: true });
  await mkdir(path.join(root, 'web-harness'), { recursive: true });

  await writeFile(
    path.join(root, 'apps/desktop/src-tauri/tauri.conf.json'),
    JSON.stringify({ productName: 'Petal', version, identifier: 'com.petal.app' }, null, 2) + '\n'
  );

  await writeFile(
    path.join(root, 'apps/desktop/src-tauri/Cargo.toml'),
    `[package]\nname = "desktop"\nversion = "${version}"\nedition = "2021"\n\n` +
      `[dependencies]\nserde = { version = "1.0" }\n`
  );

  await writeFile(
    path.join(root, 'apps/desktop/src-tauri/Cargo.lock'),
    `# This file is automatically @generated by Cargo.\nversion = 4\n\n` +
      `[[package]]\nname = "some-other-crate"\nversion = "${version}"\nsource = "registry+https://example"\n\n` +
      `[[package]]\nname = "desktop"\nversion = "${version}"\ndependencies = [\n "serde",\n]\n\n` +
      `[[package]]\nname = "zzz-later-crate"\nversion = "${version}"\n`
  );

  await writeFile(
    path.join(root, 'apps/desktop/package.json'),
    JSON.stringify({ name: 'desktop', version, license: 'Apache-2.0', dependencies: {} }, null, 2) + '\n'
  );

  await writeFile(
    path.join(root, 'apps/desktop/package-lock.json'),
    JSON.stringify(
      {
        name: 'desktop',
        version,
        lockfileVersion: 3,
        requires: true,
        packages: {
          '': { name: 'desktop', version, license: 'Apache-2.0', dependencies: {} },
          'node_modules/decoy': { version, resolved: 'https://example/decoy' },
        },
      },
      null,
      2
    ) + '\n'
  );

  await writeFile(
    path.join(root, 'web-harness/package.json'),
    JSON.stringify({ name: 'web-harness', version, license: 'Apache-2.0', dependencies: {} }, null, 2) + '\n'
  );

  await writeFile(
    path.join(root, 'web-harness/package-lock.json'),
    JSON.stringify(
      {
        name: 'web-harness',
        version,
        lockfileVersion: 3,
        requires: true,
        packages: {
          '': { name: 'web-harness', version, license: 'Apache-2.0', dependencies: {} },
          'node_modules/decoy': { version, resolved: 'https://example/decoy' },
        },
      },
      null,
      2
    ) + '\n'
  );
}

async function readAllVersions(root) {
  const tauri = JSON.parse(await readFile(path.join(root, 'apps/desktop/src-tauri/tauri.conf.json'), 'utf8'));
  const cargoToml = await readFile(path.join(root, 'apps/desktop/src-tauri/Cargo.toml'), 'utf8');
  const cargoLock = await readFile(path.join(root, 'apps/desktop/src-tauri/Cargo.lock'), 'utf8');
  const pkg = JSON.parse(await readFile(path.join(root, 'apps/desktop/package.json'), 'utf8'));
  const desktopLock = JSON.parse(await readFile(path.join(root, 'apps/desktop/package-lock.json'), 'utf8'));
  const webPkg = JSON.parse(await readFile(path.join(root, 'web-harness/package.json'), 'utf8'));
  const webLock = JSON.parse(await readFile(path.join(root, 'web-harness/package-lock.json'), 'utf8'));

  const cargoTomlVersion = cargoToml.match(/^version = "([^"]+)"/m)?.[1];
  const cargoLockDesktopVersion = cargoLock
    .slice(cargoLock.indexOf('name = "desktop"'))
    .match(/^version = "([^"]+)"/m)?.[1];

  return {
    tauri: tauri.version,
    cargoToml: cargoTomlVersion,
    cargoLockDesktop: cargoLockDesktopVersion,
    cargoLockDecoysUnchanged:
      cargoLock.includes('name = "some-other-crate"') && cargoLock.includes('name = "zzz-later-crate"'),
    package: pkg.version,
    desktopLockTop: desktopLock.version,
    desktopLockRoot: desktopLock.packages?.['']?.version,
    desktopLockDecoy: desktopLock.packages?.['node_modules/decoy']?.version,
    webPackage: webPkg.version,
    webLockTop: webLock.version,
    webLockRoot: webLock.packages?.['']?.version,
    webLockDecoy: webLock.packages?.['node_modules/decoy']?.version,
  };
}

async function withFixture(version, fn) {
  const root = await mkdtemp(path.join(tmpdir(), 'petal-bump-version-'));
  try {
    await writeFixture(root, version);
    await fn(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

async function testRealBumpUpdatesAllNineFields() {
  await withFixture('0.1.0', async (root) => {
    const { stdout } = await execFileAsync('node', [BUMP_SCRIPT, '0.2.0', '--root', root]);
    const v = await readAllVersions(root);

    assert.equal(v.tauri, '0.2.0', 'tauri.conf.json version');
    assert.equal(v.cargoToml, '0.2.0', 'Cargo.toml [package] version');
    assert.equal(v.cargoLockDesktop, '0.2.0', 'Cargo.lock desktop entry version (the 9th field)');
    assert.equal(v.package, '0.2.0', 'apps/desktop/package.json version');
    assert.equal(v.desktopLockTop, '0.2.0', 'apps/desktop/package-lock.json top-level version');
    assert.equal(v.desktopLockRoot, '0.2.0', "apps/desktop/package-lock.json packages[''].version");
    assert.equal(v.webPackage, '0.2.0', 'web-harness/package.json version');
    assert.equal(v.webLockTop, '0.2.0', 'web-harness/package-lock.json top-level version');
    assert.equal(v.webLockRoot, '0.2.0', "web-harness/package-lock.json packages[''].version");

    // Mutation check: fields at the SAME literal version string that must
    // NOT be touched -- proves the script matched the right entry, not just
    // "an" entry with that value.
    assert.equal(v.desktopLockDecoy, '0.1.0', 'unrelated node_modules entry must be untouched');
    assert.equal(v.webLockDecoy, '0.1.0', 'unrelated node_modules entry must be untouched');
    assert.ok(v.cargoLockDecoysUnchanged, 'unrelated Cargo.lock crates must be untouched');

    assert.match(stdout, /all 9 fields now read 0\.2\.0/);
  });
  console.log('PASS: real bump updates all 9 fields and leaves same-versioned decoys alone');
}

async function testDryRunWritesNothing() {
  await withFixture('0.1.0', async (root) => {
    const before = await readAllVersions(root);
    const { stdout } = await execFileAsync('node', [BUMP_SCRIPT, '0.9.9', '--root', root, '--dry-run']);
    const after = await readAllVersions(root);
    assert.deepEqual(after, before, '--dry-run must not write any file');
    assert.match(stdout, /dry run OK/);
    assert.match(stdout, /all 9 fields would read 0\.9\.9/);
  });
  console.log('PASS: --dry-run writes nothing and still reports all 9 fields');
}

async function testLockstepGateCatchesDesyncedCargoLock() {
  await withFixture('0.3.0', async (root) => {
    await execFileAsync('node', [BUMP_SCRIPT, '0.4.0', '--root', root]);

    // Sanity: lockstep passes right after a clean bump.
    await execFileAsync('node', [LOCKSTEP_SCRIPT, '0.4.0', root]);

    // Desync ONLY Cargo.lock's desktop entry -- exactly what `cargo build`
    // does mid-build when Cargo.lock is left stale (the scenario item 6
    // describes).
    const cargoLockPath = path.join(root, 'apps/desktop/src-tauri/Cargo.lock');
    let cargoLock = await readFile(cargoLockPath, 'utf8');
    const nameIdx = cargoLock.indexOf('name = "desktop"');
    const match = cargoLock.slice(nameIdx).match(/^version = "([^"]+)"/m);
    const idx = nameIdx + match.index;
    cargoLock = cargoLock.slice(0, idx) + 'version = "0.3.0"' + cargoLock.slice(idx + match[0].length);
    await writeFile(cargoLockPath, cargoLock);

    let caught = false;
    try {
      await execFileAsync('node', [LOCKSTEP_SCRIPT, '0.4.0', root]);
    } catch (e) {
      caught = true;
      const output = `${e.stdout ?? ''}${e.stderr ?? ''}`;
      assert.match(output, /cargoLockDesktop/, 'failure must name the field that actually drifted');
      assert.match(output, /"value":"0\.3\.0"|"value": "0\.3\.0"/, 'failure must show the stale value');
    }
    assert.ok(caught, 'lockstep gate must fail when Cargo.lock desktop version drifts');
  });
  console.log('PASS: lockstep gate catches a deliberately desynced Cargo.lock desktop version (the 9th field)');
}

async function main() {
  await testRealBumpUpdatesAllNineFields();
  await testDryRunWritesNothing();
  await testLockstepGateCatchesDesyncedCargoLock();
  console.log('\nALL bump-version / lockstep tests passed.');
}

main().catch((err) => {
  fail(err.stack || err.message);
});
